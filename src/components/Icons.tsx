// ไอคอนวาดด้วย SVG เอง ใช้สีตามตัวหนังสือรอบข้าง (currentColor) จึงเปลี่ยนสีตามโหมดมืดได้เอง
function Svg({ className = "h-5 w-5", children }: { className?: string; children: ReactNode }) {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.8}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      aria-hidden="true"
    >
      {children}
    </svg>
  );
}

